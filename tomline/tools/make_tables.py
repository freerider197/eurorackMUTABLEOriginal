#!/usr/bin/env python3
"""Generates tomline/tables.h. Run: python3 tomline/tools/make_tables.py > tomline/tables.h"""
import math

FR = 72e6 / 6 / (12.5 * 6 + 71.5 * 2 + 55.5 * 2 + 28.5 * 2)  # ADC scan rate, see streams/drivers/adc.cc

def arr(name, ctype, values, per_line=8):
    out = ["const %s %s[%d] = {" % (ctype, name, len(values))]
    for i in range(0, len(values), per_line):
        out.append("  " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)

sine = [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)]
exp2 = [int(round((2 ** (i / 256.0)) * (1 << 30))) for i in range(257)]
c1 = 32.70319566
inc_c1 = int(round(c1 / FR * (1 << 32)))

print("// Generated by tomline/tools/make_tables.py. Do not edit.")
print("#ifndef TOMLINE_TABLES_H_\n#define TOMLINE_TABLES_H_\n\n#include <stdint.h>\n\nnamespace tomline {\n")
print("// Firmware sample rate: one ADC scan of the 6 CV inputs.")
print("const float kSampleRate = %.4ff;" % FR)
print("// Phase increment of C1 (32.703 Hz) at kSampleRate.")
print("const uint32_t kIncrementC1 = %d;\n" % inc_c1)
print(arr("lut_sine", "int16_t", sine))
print("\n// 2^(i/256) in Q30.")
print(arr("lut_exp2_q30", "uint32_t", exp2, 6))
print("\n}  // namespace tomline\n\n#endif  // TOMLINE_TABLES_H_")
